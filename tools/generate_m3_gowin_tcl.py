#!/usr/bin/env python3
"""Generate a Gowin 1.9.9-compatible headless build Tcl from the .gprj.

Gowin 1.9.9 Beta/Education does not implement open_project in gw_sh.
Generate the supported set_device / add_file / set_option / run flow
from the *current* GUI project XML. This avoids maintaining a second,
potentially stale list of the ~120 HDL, pin and timing files.

Files of type file.other (.mem/.hex) are verified on disk but intentionally
not passed to add_file: Gowin add_file accepts HDL, netlists and constraints;
the memory images are loaded by RTL $readmemh from the project paths.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET


GOWIN_FILE_TYPES = {
    "file.verilog": "verilog",  # includes .sv and .v
    "file.vhdl": "vhdl",
    "file.cst": "cst",
    "file.sdc": "sdc",
    "file.fdc": "fdc",
    "file.netlist": "netlist",
}


def tcl_literal(value: str) -> str:
    """Use braced Tcl literals: Windows paths are normalized to / first."""
    if any(char in value for char in "{}\\\r\n"):
        raise ValueError(f"Unsupported Tcl path/string characters: {value!r}")
    return "{" + value + "}"


def generate(project_path: Path, output_path: Path, flow: str) -> dict:
    project_path = project_path.resolve()
    board_dir = project_path.parent
    root = ET.parse(project_path).getroot()
    device = root.find("Device")
    if device is None:
        raise RuntimeError(f"Missing Device entry in {project_path}")
    part_number = device.get("pn")
    device_name = device.get("name")
    if not part_number or not device_name:
        raise RuntimeError("Gowin .gprj must specify Device name and pn")

    cfg_path = board_dir / "impl" / "project_process_config.json"
    if not cfg_path.is_file():
        raise RuntimeError(f"Missing GUI process configuration: {cfg_path}")
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    top = cfg.get("TopModule", "top")
    out_base = cfg.get("OUTPUT_BASE_NAME", project_path.stem)
    if cfg.get("Synthesize_tool") not in ("GowinSyn", "gowinsynthesis"):
        raise RuntimeError("Unexpected GUI synthesis tool, refusing silent change")

    files = root.findall("./FileList/File")
    if not files:
        raise RuntimeError(f"No HDL files in {project_path}")
    tcl = [
        "# Automatically generated by tools/generate_m3_gowin_tcl.py",
        "# Gowin 1.9.9 does NOT support open_project in gw_sh.",
        "# Run from the .gprj directory via gw_sh.exe <this_file.tcl>.",
        "# Do not edit: regenerate from the authoritative .gprj on each build.",
        "if {[catch {",
        f"    set_device -name {tcl_literal(device_name)} {tcl_literal(part_number)}",
    ]
    enabled_count = 0
    other_count = 0
    for item in files:
        relpath = item.get("path")
        kind = item.get("type")
        enabled = item.get("enable", "1") == "1"
        if not relpath or not kind:
            raise RuntimeError("Gowin project contains an incomplete File entry")
        # The gprj paths use forward slashes, even on Windows.
        normalized = relpath.replace("\\", "/")
        actual = (board_dir / normalized).resolve()
        if not actual.is_file():
            raise RuntimeError(f"Missing project source: {normalized} ({actual})")
        if not enabled:
            continue
        if kind == "file.other":
            other_count += 1
            continue
        if kind not in GOWIN_FILE_TYPES:
            raise RuntimeError(f"Unsupported enabled project file kind {kind}: {relpath}")
        tcl.append(f"    add_file -type {GOWIN_FILE_TYPES[kind]} {tcl_literal(normalized)}")
        enabled_count += 1

    if enabled_count < 40:
        raise RuntimeError(f"Suspiciously few design files: {enabled_count}")
    if not any("fpga_sd_burst.sv" in line for line in tcl):
        raise RuntimeError("M3 FPGA burst RTL missing from generated HDL list")
    if not any("a2n20v2_enhanced.sdc" in line for line in tcl):
        raise RuntimeError("Critical timing constraints missing from generated HDL list")
    if not any("a2n20v2_enhanced.cst" in line for line in tcl):
        raise RuntimeError("Critical pin constraints missing from generated HDL list")

    tcl += [
        f"    set_option -output_base_name {tcl_literal(out_base)}",
        "    set_option -synthesis_tool gowinsynthesis",
        f"    set_option -top_module {tcl_literal(top)}",
        "    set_option -verilog_std sysv2017",
        "    set_option -vhdl_std vhd1993",
        # Original GUI include-path list is empty, but top.sv includes
        # datetime.svh from board/hdl. Make it explicit in headless mode.
        "    set_option -include_path {hdl;../../hdl}",
        f"    run {flow}",
        "} m3_tcl_error m3_tcl_options]} {",
        '    puts "M3_GOWIN_TCL_FAILED: $m3_tcl_error"',
        "    exit 31",
        "}",
        'puts "M3_GOWIN_TCL_COMPLETED"',
        "exit 0",
        "",
    ]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    # Gowin 1.9.9's Tcl parser prefers UTF-8 without a BOM.
    output_path.write_text("\n".join(tcl), encoding="utf-8")
    return {"device": part_number, "top": top, "flow": flow,
            "sources": enabled_count, "data_files": other_count,
            "script": str(output_path)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--flow", choices=("syn", "all"), default="all")
    args = parser.parse_args()
    try:
        info = generate(args.project, args.out, args.flow)
    except (OSError, ValueError, RuntimeError, ET.ParseError) as exc:
        print(f"M3 Gowin script generation FAILED: {exc}", file=sys.stderr)
        return 1
    print("M3 headless Tcl ready: " + json.dumps(info, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
