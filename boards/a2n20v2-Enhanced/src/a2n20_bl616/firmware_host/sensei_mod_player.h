#ifndef SENSEI_MOD_PLAYER_H
#define SENSEI_MOD_PLAYER_H

/* Four-channel ProTracker tick interpreter for the Sensei P1D FPGA FIFO.
 * Song pattern assets are generated locally from user-provided MODs; no
 * copyrighted patterns or samples are committed to this repository. */
#include <stdint.h>
#include <stdbool.h>

typedef void (*sensei_doc_event_t)(uint16_t when, uint8_t doc_reg, uint8_t data);
typedef struct {
    const uint8_t *rows;     /* flattened played 16-byte rows */
    uint16_t count;
    const uint8_t *catalog;  /* P2R runtime: 32x8, legacy tests 32x4 */
} sensei_mod_song_t;

typedef struct {
    uint16_t period, target, delayed_period;
    uint8_t instrument, volume, fx, param;
    uint8_t porta_speed, vib_speed, vib_depth, vib_phase;
    uint8_t volslide, delayed_inst, delayed_tick;
    uint8_t last_ctrl;
    uint8_t last_effect;
} sensei_mod_chan_t;

typedef struct {
    const sensei_mod_song_t *song;
    sensei_mod_chan_t ch[4];
    uint16_t row;
    uint8_t tick, speed, bpm, done;
    uint32_t next_tick_fp;  /* FPGA milliseconds Q16.16 */

    /* P2 raw MOD mode: preserve original pattern/order structure instead
     * of building a flattened event stream in RAM or offline. */
    sensei_mod_song_t runtime_song;
    const uint8_t *order_table;
    uint8_t runtime_mode, order_count, order_pos;
    uint8_t audition_mask; /* bits 0..3: enabled MOD channels, P2U */
    uint8_t channel_pan[4]; /* DOC 0x10 left; NTP may override channels */
    uint32_t note_starts[4]; /* attempted note/retrigger starts per channel */
    uint8_t jump_pending, break_pending, loop_pending;
    uint8_t jump_to, break_row, loop_to;
    uint8_t loop_start[4], loop_count[4];
    uint32_t visited_rows; /* runaway Bxx/E6x loop guard */
} sensei_mod_player_t;

/* Raw MOD player: samples must already be uploaded to DOC RAM.
 * patterns: 1024 bytes per standard four-channel pattern
 * orders: list of pattern numbers from original MOD header
 * catalog: runtime DOC instrument table generated by sensei_mod_decode
 * Use only after DMA completion is confirmed. */
bool sensei_mod_init_runtime(sensei_mod_player_t *state,
                            const uint8_t *patterns,
                            const uint8_t *orders, uint8_t order_count,
                            const uint8_t *catalog, uint16_t now);

/* Legacy P1E test API, retained only as a known-good diagnostics reference. */
bool sensei_mod_init(sensei_mod_player_t *state, uint8_t song_id, uint16_t now);
bool sensei_mod_tick(sensei_mod_player_t *state, sensei_doc_event_t emit);
uint16_t sensei_mod_next_ms(const sensei_mod_player_t *state);
bool sensei_mod_done(const sensei_mod_player_t *state);
bool sensei_mod_available(void);

#endif
